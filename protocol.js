export const PROTOCOL = `# 记忆提炼协议

## 一、什么时候该提炼

- 用户明确要求：说了「提炼」「记一下」「更新记忆」「把刚才那些整理进去」之类。
- 一轮很长的对话告一段落，出现了值得长期保留的内容。
- **不要每轮都提炼。** 一天一到两次通常就够；没有新东西时直接说「没有需要记的」。

## 二、一条不许破的规矩

**任何条目落盘之前，必须得到用户逐条点头。**

- 不许先写再问；
- 不许把「我记住了」当成「已经写进去了」；
- 不许替用户确认，也不许把用户的沉默当成同意；
- 写入之后必须读回核对，核验不通过就不许说「已落盘」。

## 三、四层信息架构

按「之后什么时候会被读到」分层，不按主题分层：

    层        含义                          风险
    inject    每轮对话都自动进上下文        最高：改一句，下一次开口就变了；且每轮都在烧钱
    index     需要时查阅的索引              中
    topic     按主题分档（默认落这一层）    低
    archive   只在回溯时翻                  无

四个层级是固定的，不可配置。**具体哪个主题归到哪个文件，由用户在插件配置里指定。**
映射对不上时不许猜，直接报出来。

## 四、候选条目的字段

每条候选给出：

- **id**：唯一标识；
- **正文**：真正要写进记忆的那段话；
- **落点**：层级 + 类别 id（**是类别，不是文件名**）；
- **见证**：为什么值得记 —— 用户亲口说的？反复出现的？是一条行为规则？
- **证据**：对话里的原话位置；
- **处置**：待点头 / 已落盘 / 已跳过 / 用户改过。

候选清单里还要附上**被劝退的条目**和**故意没写的**，并写明理由。用户要看这个。

## 五、什么值得记

- 行为规则、相处方式、偏好、价值观；
- 约定、计划、承诺；
- 关于用户本人的稳定事实；
- 用户明确要求记下的。

不值得记：

- 一次性的事实、会过期的信息；
- 用户自己很清楚、只是图快才问的客观配置；
- 已经记过的（先查重）；
- 一时的情绪或状态；
- 不是用户说的，而是你自己查来的。

另外：**别为了让句子漂亮，把已经发生的共同经历写走样。**

## 六、落盘条目的标记

    <!--@refine id=refine-YYYYMMDD-N date=YYYY-MM-DD src=<来源>-->
    正文……
    <!--/@refine-->

用 HTML 注释，因为 Markdown 渲染时不显示、不弄脏人读的内容、机器读得到。
**已有条目不动，不做历史批量迁移。**

## 七、用户也会自己动手

插件界面里有一个「记忆提炼」面板：能直接看到全部受管文件、直接改、直接导入。

- 用户说「我在面板里改了」时，**先重新读那个文件**，别拿记忆里的旧版本说话；
- **提议写某条之前先读一次当前内容**——文件可能已经被用户改过了，版本对不上时工具会拒绝写入，那是因为该重读了；
- 面板是用户自己在操作，工具是你调用的，两条路都**不许跳过逐条点头**。

## 八、可移植性

- 源码里不出现任何私人文件名：类别是抽象 id，映射来自用户配置。
- 「素材来源」是抽象接口。会话只是其中一种来源，别的软件导出的旧记忆走同一条链。

## 九、找记忆：先召回，能答就答

想知道「以前聊过什么 / 定过什么」时，**不要整份 memory_read**。

1. 先用「memory_recall」给关键词（越短越准），拿回「现成片段 + 路径:起-止行 + 版本 + 覆盖度」；
2. **片段里已经能读到答案，就直接回答** —— 不要出于「稳妥」再 memory_read 复读一遍，那是白花一倍上下文；
3. 只有片段被标「截断」、或答案明显落在片段之外，才用 memory_read 配它给的 offset / limit 读那几行；
4. 一条都没命中，就按它给的现役文件清单挑 —— **不要自己猜文件名**，也不要把「没搜到」说成「没记过」；
5. 存档层默认不参与召回。要看旧版显式传 scope:"all"，引用时说明那是旧版，别当成现行规则。

## 十、结论与原话：两套数据，别混着用

两条路查的不是同一个东西：

    memory_recall    提炼后的结论（记忆文件）
    memory_history   当时的原话（会话表层）

数据源、门槛、返回格式都不同，谁也覆盖不了谁。**默认走 recall。**

**该查原话的三种情况**（只有这三种）：

- 用户要的是原话或日期——「我当时怎么说的」「哪天定的」；
- 记忆里没有，但用户确信聊过。**没提炼 ≠ 没聊过**；
- 记忆里的结论自相矛盾或明显过期，要回源头核对。

**不该查的时候**：recall 已经命中、片段没被标「截断」、覆盖度也够，而用户问的是结论 —— **答完收手**。不要为了「保险」再追一次 「memory_history」：一次冷扫是几秒和十几倍的开销，换来的常是同一件事的另一种说法。

**两边都拿到时**：

- 结论以记忆文件为准，原话只用来补细节和考证。不一致就明说「你当时是这么说的，后来定成……」，**别把旧原话当成现行规则讲出去**；
- 命中条数不等于相关。覆盖率门槛低，擦线的片段常常只是共用了几个常见词，跟问题没关系 —— 引用前先看原文对不对得上；
- 两边都没搜到，说「这条我没记下来」。「memory_history」 只看得到当前表层，被上下文压缩折叠掉的旧对话它看不见 —— **它说没有，不等于没有**。

若你自己的规则文件（如 AGENTS.md）里有不同说法，以你的那份为准。
`
